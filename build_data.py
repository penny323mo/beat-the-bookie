#!/usr/bin/env python3
"""
build_data.py - Parse SP1_2526.csv and SP1_2425.csv into data.js.
Reads both CSVs with utf-8-sig encoding and writes window.MATCHES.
"""

import csv
import json
import os
import sys

def parse_csv(filepath, season_name):
    matches = []
    if not os.path.exists(filepath):
        print(f"Warning: {filepath} not found.", file=sys.stderr)
        return matches

    with open(filepath, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            home = row.get("HomeTeam", "").strip()
            away = row.get("AwayTeam", "").strip()
            if not home or not away:
                continue

            fthg_str = row.get("FTHG", "").strip()
            ftag_str = row.get("FTAG", "").strip()
            ftr = row.get("FTR", "").strip().upper()
            if not fthg_str or not ftag_str or ftr not in ("H", "D", "A"):
                continue

            try:
                fthg = int(fthg_str)
                ftag = int(ftag_str)
            except ValueError:
                continue

            # Convert DD/MM/YYYY to ISO YYYY-MM-DD
            date_str = row.get("Date", "").strip()
            parts = date_str.split("/")
            if len(parts) == 3:
                try:
                    day, month, year = int(parts[0]), int(parts[1]), int(parts[2])
                    iso_date = f"{year:04d}-{month:02d}-{day:02d}"
                except ValueError:
                    iso_date = date_str
            else:
                iso_date = date_str

            # Odds: try B365 first, fallback to Avg
            h, d, a = None, None, None
            for prefix in ("B365", "Avg"):
                h_val = row.get(f"{prefix}H", "").strip()
                d_val = row.get(f"{prefix}D", "").strip()
                a_val = row.get(f"{prefix}A", "").strip()
                try:
                    if h_val and d_val and a_val:
                        h_f = float(h_val)
                        d_f = float(d_val)
                        a_f = float(a_val)
                        if h_f > 0 and d_f > 0 and a_f > 0:
                            h, d, a = h_f, d_f, a_f
                            break
                except ValueError:
                    continue

            if h is None or d is None or a is None:
                continue

            # Halftime score and shots (optional for reveal)
            hthg = None
            htag = None
            if row.get("HTHG", "").strip() != "":
                try:
                    hthg = int(row["HTHG"])
                except ValueError:
                    hthg = None
            if row.get("HTAG", "").strip() != "":
                try:
                    htag = int(row["HTAG"])
                except ValueError:
                    htag = None

            hs = None
            as_shots = None
            if row.get("HS", "").strip() != "":
                try:
                    hs = int(row["HS"])
                except ValueError:
                    hs = None
            if row.get("AS", "").strip() != "":
                try:
                    as_shots = int(row["AS"])
                except ValueError:
                    as_shots = None

            match = {
                "season": season_name,
                "date": iso_date,
                "home": home,
                "away": away,
                "fthg": fthg,
                "ftag": ftag,
                "ftr": ftr,
                "odds": {
                    "h": round(h, 2),
                    "d": round(d, 2),
                    "a": round(a, 2)
                },
                "hthg": hthg,
                "htag": htag,
                "hs": hs,
                "as": as_shots
            }
            matches.append(match)

    return matches


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    file_2526 = os.path.join(script_dir, "SP1_2526.csv")
    file_2425 = os.path.join(script_dir, "SP1_2425.csv")
    output_js = os.path.join(script_dir, "data.js")

    matches_2526 = parse_csv(file_2526, "2025/26")
    matches_2425 = parse_csv(file_2425, "2024/25")

    all_matches = matches_2526 + matches_2425
    print(f"Loaded {len(matches_2526)} matches from 2025/26")
    print(f"Loaded {len(matches_2425)} matches from 2024/25")
    print(f"Total: {len(all_matches)} matches")

    with open(output_js, "w", encoding="utf-8") as f:
        f.write("// Generated by build_data.py - Do not edit directly\n")
        f.write("window.MATCHES = ")
        json.dump(all_matches, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Successfully wrote data to {output_js}")


if __name__ == "__main__":
    main()
